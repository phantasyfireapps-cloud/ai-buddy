#!/usr/bin/env node
// Generates the SQL migration that loads the personality presets and avatars into Supabase
// from the JSON files in /presets. Run after editing presets: `node scripts/generate-catalogue-migration.mjs`
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "supabase/migrations/20261101120100_catalogue_seed.sql");

const q = (v) => `'${String(v).replaceAll("'", "''")}'`;
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

export function buildCatalogueSql() {
  const avatars = JSON.parse(readFileSync(join(root, "presets/avatars.json"), "utf8")).avatars;
  const dir = join(root, "presets/personalities");
  const presets = readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => {
      const { $schema, ...preset } = JSON.parse(readFileSync(join(dir, f), "utf8"));
      return preset;
    });

  const lines = [
    "-- GENERATED by scripts/generate-catalogue-migration.mjs from /presets. Do not edit by hand.",
    "",
  ];
  for (const a of avatars) {
    lines.push(
      `insert into public.avatars (id, name, asset_ref, animation_config, appearance) values (${q(a.id)}, ${q(a.name)}, ${q(a.assetRef)}, ${j(a.animation)}, ${j(a.appearance)})`,
      `  on conflict (id) do update set name = excluded.name, asset_ref = excluded.asset_ref, animation_config = excluded.animation_config, appearance = excluded.appearance;`,
    );
  }
  lines.push("");
  for (const p of presets) {
    lines.push(
      `insert into public.personality_presets (id, version, name, config, default_avatar_id, voice_preferences) values (${q(p.id)}, ${p.version}, ${q(p.name)}, ${j(p)}, ${q(p.avatar.defaultAvatarId)}, ${j(p.voice)})`,
      `  on conflict (id, version) do nothing;`,
    );
  }
  return lines.join("\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(out, buildCatalogueSql());
  console.log(`Wrote ${out}`);
}
